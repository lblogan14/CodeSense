#!/usr/bin/env node
/*
 * Re-applies the CodeSense touch calibration to the Moddable CoreS3 target
 * driver. The Moddable `m5stack_cores3` target forwards RAW FT6x06 coordinates
 * to Piu (its manifest declares a flip/fit config the driver never applies), so
 * on-device taps land scaled/offset from the 320x240 screen. This inserts a
 * coordinate remap into M5StackCoreS3Touch.js's sample().
 *
 * Why a script and not a repo file: the driver lives in the Moddable SDK, not
 * this repo, so it's lost on an SDK reinstall/update. Run this to restore it:
 *
 *     node firmware/m5-cores3/apply-touch-calibration.mjs
 *
 * Idempotent (skips if already applied). Constants are PER-UNIT — measure yours
 * per firmware/m5-cores3/SETUP.md ("Touch calibration") and edit CAL below.
 * Candidate to upstream to Moddable (make the driver honor its own fit config).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

// ── per-unit calibration: corrected = (raw <op> off) / scale, clamped ──
const CAL = {
  x: { off: '+ 11', scale: 1.185 }, // right side was clamping off controls
  y: { off: '- 32', scale: 0.9 }, // less drift toward the bottom
};

const MODDABLE = process.env.MODDABLE;
if (!MODDABLE) {
  console.error('✗ MODDABLE env var not set — open a Moddable build shell first.');
  process.exit(1);
}
const file = join(
  MODDABLE,
  'build',
  'devices',
  'esp32',
  'targets',
  'm5stack_cores3',
  'M5StackCoreS3Touch.js',
);
if (!existsSync(file)) {
  console.error(`✗ driver not found: ${file}`);
  process.exit(1);
}

const MARKER = 'CodeSense touch calibration';
let src = readFileSync(file, 'utf8');
if (src.includes(MARKER)) {
  console.log('✓ already calibrated — nothing to do');
  process.exit(0);
}

const block = `
    // ── ${MARKER} ────────────────────────────────
    // Remap raw FT6x06 coords into 320x240 display space (this target's driver
    // never applies its own fit config). Per-unit; regenerated by
    // firmware/m5-cores3/apply-touch-calibration.mjs — see SETUP.md.
    if (points) {
      for (let i = 0; i < points.length; i++) {
        const p = points[i];
        const x = Math.round((p.x ${CAL.x.off}) / ${CAL.x.scale});
        const y = Math.round((p.y ${CAL.y.off}) / ${CAL.y.scale});
        p.x = x < 0 ? 0 : x > 319 ? 319 : x;
        p.y = y < 0 ? 0 : y > 239 ? 239 : y;
      }
    }
`;

const anchor = '    return points;';
const idx = src.lastIndexOf(anchor);
if (idx < 0) {
  console.error('✗ could not find "return points;" in sample() — SDK driver changed; patch manually per SETUP.md.');
  process.exit(1);
}
src = src.slice(0, idx) + block + '\n' + src.slice(idx);
writeFileSync(file, src);
console.log(`✓ applied touch calibration to ${file}`);
console.log('  reflash the orb for it to take effect.');
